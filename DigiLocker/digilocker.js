    function createField(field, index) {

        const group = document.createElement("div");
        group.className = "demo-form-group";

        const label = document.createElement("label");
        label.textContent = field.name;
        label.htmlFor = "demo-field-" + index;

        let input;

        if (field.type === "select") {

            input = document.createElement("select");

            const first = document.createElement("option");
            first.value = "";
            first.textContent = "Select " + field.name;

            input.appendChild(first);

            field.options.forEach(function (item) {

                const option = document.createElement("option");
                option.value = item;
                option.textContent = item;

                input.appendChild(option);

            });

        } else {

            input = document.createElement("input");
            input.type = field.type;
            input.placeholder = "Enter " + field.name.toLowerCase();

            if (field.type === "number") {
                input.min = field.min;
                input.max = field.max;
                input.step = "1";
            }
        }

        input.id = label.htmlFor;
        input.required = true;

        group.appendChild(label);
        group.appendChild(input);

        return group;
    }

