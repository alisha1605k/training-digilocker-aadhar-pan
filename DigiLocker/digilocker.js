    // =====================================
    // OPEN EACH SERVICE
    // =====================================

    function openService(index) {

        const service = services[index];

        if (!service) return;

        const oldForm = document.getElementById("serviceDemoForm");
        const oldResult = document.getElementById("serviceDemoResult");

        if (oldForm) oldForm.remove();
        if (oldResult) oldResult.remove();

        modalTitle.textContent = service.title;
        modalMessage.textContent = service.message;

        const form = document.createElement("form");
        form.id = "serviceDemoForm";
        form.className = "demo-form";

        service.fields.forEach(function (field, i) {
            form.appendChild(createField(field, i));
        });

        const submit = document.createElement("button");
        submit.type = "submit";
        submit.className = "demo-submit";
        submit.textContent = "Generate Result";

        const reset = document.createElement("button");
        reset.type = "reset";
        reset.className = "demo-reset";
        reset.textContent = "Reset Form";

        form.append(submit, reset);

        modalMessage.insertAdjacentElement("afterend", form);

        form.addEventListener("submit", function (event) {

            event.preventDefault();

            const values = service.fields.map(function (field, i) {
                return form.querySelector("#demo-field-" + i).value.trim();
            });

            const old = document.getElementById("serviceDemoResult");
            if (old) old.remove();

            const result = createResult(index, values);

            form.insertAdjacentElement("afterend", result);

        });

        form.addEventListener("reset", function () {

            const old = document.getElementById("serviceDemoResult");
            if (old) old.remove();

        });

        modal.classList.add("active");

    }

